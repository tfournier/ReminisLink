/** M16 on Android: the fake pak of the demo mode, through the real signed client (no network). */
class DemoTest {
    private val demo = DemoConsole("Demo Handheld") { "Demo cheat $it" }
    private val client get() = demo.client

    @After
    fun tearDown() = demo.close()

    private suspend fun game(name: String) = client.allGames().games.first { it.name == name }

    @Test
    fun consoleLibraryAndNoProductName() = runBlocking {
        val hello = client.hello()
        assertEquals("Demo Handheld", hello.deviceName)
        assertEquals(FakePak.MODEL, hello.model)
        assertTrue(demo.endpoint.host.endsWith(".invalid"))
        val device = client.device()
        assertEquals(demo.deviceId, device.deviceId)
        val systems = client.systems()
        assertEquals(listOf("Disc Console", "Handheld Advance", "Pocket Classic"), systems.map { it.label })
        val all = client.allGames()
        assertEquals(
            setOf("Thistledown Isles", "Brambleway Dash", "Quillwork Tactics", "Cartographe Égaré", "Mosslight Maze 🌙", "Orrery of Nine Tides"),
            all.games.map { it.name }.toSet(),
        )
        val isles = all.games.first { it.name == "Thistledown Isles" }
        assertEquals(12, isles.cheatCount)
        val detail = client.game(isles.id)
        assertTrue(detail.hasSave)
        assertEquals(3, detail.stateCount)
        val cheats = client.cheats(isles.id)
        assertEquals("Demo cheat 1", cheats.cheats.first().description)
        assertEquals(mapOf("handler" to "0"), cheats.cheats.first().extra)
        // Downloads are served whole (generated bytes for the large made-up ROM).
        val rom = detail.files.first { it.role == GameFileRoles.ROM }
        val out = java.io.ByteArrayOutputStream()
        assertEquals(rom.sizeBytes, client.download(DownloadSource.GameFile(isles.id, rom.fileId!!), out))
    }

    @Test
    fun cheatsSavesAndStates() = runBlocking {
        val isles = game("Thistledown Isles")
        val list = client.cheats(isles.id)
        val toggled = list.cheats.mapIndexed { i, c -> if (i == 1) c.copy(enabled = true) else c }
        val saved = client.replaceCheats(isles.id, CheatsUpdate(toggled), list.etag)
        assertTrue(saved.cheats[1].enabled)
        try {
            client.replaceCheats(isles.id, CheatsUpdate(toggled), list.etag)
            fail("stale etag accepted")
        } catch (e: ApiException.Server) {
            assertEquals(412, e.status)
        }
        val imported = client.importCheats(isles.id, CheatImportRequest(CheatImportSource.Sd(client.sdFiles(SdFileType.CHT).first().id), CheatImportMode.MERGE))
        assertEquals(14, imported.total)

        val backup = client.createSaveBackup(isles.id, "Mine")
        assertEquals("Mine", client.saveBackups(isles.id).first().label)
        assertNotNull(client.restoreSaveBackup(isles.id, backup.id).backup)

        val slots = client.states(isles.id)
        assertEquals(listOf(0, 1, 2), slots.userSlots.map { it.slot })
        assertTrue(slots.slots.first { it.slot == 0 }.wasRestored)
        assertFalse("restored is reported once", client.states(isles.id).slots.first { it.slot == 0 }.wasRestored)
        assertTrue(client.lockState(isles.id, 2).locked)
        try {
            client.deleteState(isles.id, 2)
            fail("locked state deleted")
        } catch (e: ApiException.Server) {
            assertEquals(ErrorCodes.STATE_LOCKED, e.code)
        }
        client.unlockState(isles.id, 2)
        val moved = client.deleteState(isles.id, 2)
        assertTrue(client.trash().entries.any { it.id == moved.trashEntryId })
        assertNotNull(client.stateThumbnail(isles.id, 0))
    }

    @Test
    fun uploadPatchPakAndTrashRestore() = runBlocking {
        val system = client.systems().first { it.tag == "HA" }
        val bytes = ByteArray(2_500_000) { (it % 251).toByte() }
        val file = java.io.File.createTempFile("demo", ".hab").apply { writeBytes(bytes) }
        try {
            val created = client.createUpload(CreateUploadRequest(UploadTarget.Rom(system.id, "Lanternfish.hab"), bytes.size.toLong(), "00"))
            var offset = 0L
            while (offset < bytes.size) {
                offset = client.sendChunk(created.uploadId, offset, file, minOf(created.chunkSize, bytes.size - offset))
            }
            val gameId = client.completeUpload(created.uploadId).gameId!!
            assertEquals("Lanternfish", client.game(gameId).name)
            val out = java.io.ByteArrayOutputStream()
            client.download(DownloadSource.GameFile(gameId, client.game(gameId).files.first().fileId!!), out)
            assertTrue(out.toByteArray().contentEquals(bytes))

            // A patch from the SD card makes a new file once its job ends.
            val patch = client.sdFiles(SdFileType.PATCH).first()
            val job = client.patchGame(gameId, PatchRequest(PatchSource.Sd(patch.id), PatchOutputMode.NEW_FILE, "Lanternfish (patched).hab"))
            val done = withTimeout(10_000) {
                var j = client.job(job.jobId)
                while (!j.isFinished) {
                    delay(100)
                    j = client.job(job.jobId)
                }
                j
            }
            assertTrue(done.succeeded)
            assertEquals("Lanternfish (patched)", client.game(done.resultGameId!!).name)

            // Deleted, then restored from the trash with the same id.
            val moved = client.deleteGame(gameId, keepSave = false)
            assertTrue(client.allGames().games.none { it.id == gameId })
            val preview = client.trashRestorePreview(moved.trashEntryId)
            assertFalse(preview.conflict)
            client.restoreTrashEntry(moved.trashEntryId, TrashRestoreConflict.FAIL)
            assertTrue(client.allGames().games.any { it.id == gameId })

            // ReminisLink itself is never deleted.
            val self = client.paks().first { it.isSelf }
            try {
                client.deletePak(self.pakId)
                fail("ReminisLink deleted")
            } catch (e: ApiException.Server) {
                assertTrue(e.isPakSelfConflict)
            }
            val clock = client.paks().first { it.name == "Clock" }
            client.deletePak(clock.pakId)
            assertTrue(client.paks().none { it.name == "Clock" })
        } finally {
            file.delete()
        }
    }

    @Test
    fun eventsFollowTheChanges() = runBlocking {
        val source = client.openEvents()
        val parser = SseParser()
        val buffer = ByteArray(1024)
        suspend fun next(): PakEvent = withTimeout(5_000) {
            while (true) {
                val n = source.read(buffer)
                if (n < 0) error("end of stream")
                val events = parser.feed(buffer, 0, n).filterIsInstance<SseItem.Event>().mapNotNull { PakEvent.parse(it.event) }
                if (events.isNotEmpty()) return@withTimeout events.first()
            }
            @Suppress("UNREACHABLE_CODE")
            error("unreachable")
        }
        assertTrue(next() is PakEvent.Hello)
        val isles = game("Thistledown Isles")
        client.createSaveBackup(isles.id, null)
        val library = next() as PakEvent.Library
        assertEquals(setOf(isles.systemId), library.library.affectedSystems)
        demo.pak.sendShutdown()
        assertEquals("quit", (next() as PakEvent.Shutdown).shutdown.reason)
        source.cancel()
        assertEquals(0, demo.pak.openStreams)
    }
}
