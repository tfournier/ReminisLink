        emit("paks", JsonObject(emptyMap()))
        return json(r, 200, buildJsonObject { put("trashEntryId", item.id); put("moved", JsonArray(item.files.map(::JsonPrimitive))); put("movedBytes", item.sizeBytes) })
    }

