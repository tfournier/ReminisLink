    private fun emptyTrash(r: Request): Response {
        if (r.header("X-RL-Confirm") != "empty-trash") return error(r, 400, "invalid_request", "Missing confirmation")
        val freed = trash.sumOf { it.sizeBytes }
        trash.clear()
        library(null)
        return json(r, 200, buildJsonObject { put("freedBytes", freed) })
    }

    /** Whether the place of a payload is taken; with [suffix], under that free name. */
    private fun taken(payload: Payload?, suffix: String = ""): Boolean = when (payload) {
        null -> true
        is Payload.Game -> payload.system.games.any {
            it.parent == payload.game.parent && it.fileName.equals(payload.game.name + suffix + payload.game.extension, ignoreCase = true)
        }
        is Payload.Pak -> paks.any { it.name.equals(payload.pak.name + suffix, ignoreCase = true) }
        is Payload.Backup -> suffix.isEmpty() && payload.game.backups.any { it.id == payload.backup.id }
        is Payload.State -> suffix.isEmpty() && payload.game.slots.containsKey(payload.slot)
        is Payload.Art -> suffix.isEmpty() && payload.game.art != null
    }

    private fun freeNumber(payload: Payload?): Int? {
        if (payload !is Payload.Game && payload !is Payload.Pak) return null
        return (2..99).firstOrNull { !taken(payload, " ($it)") }
    }

    private fun renamed(name: String, number: Int?): String {
        if (number == null) return name
        val dot = name.lastIndexOf('.').takeIf { it > 0 } ?: name.length
        return name.substring(0, dot) + " ($number)" + name.substring(dot)
    }

    private fun trashRoute(r: Request, m: String, s: List<String>, body: ByteArray): Response {
        val entry = trash.firstOrNull { it.id == s[1] } ?: return error(r, 404, "not_found", "Trash entry not found")
        return when {
            m == "DELETE" && s.size == 2 -> {
                if (r.header("X-RL-Confirm") != "empty-trash") return error(r, 400, "invalid_request", "Missing confirmation")
                trash.remove(entry)
                library(null)
                json(r, 200, buildJsonObject { put("freedBytes", entry.sizeBytes) })
            }
            m == "GET" && s.size == 3 && s[2] == "restore" -> json(r, 200, restorePreview(entry))
            m == "POST" && s.size == 3 && s[2] == "restore" -> restore(r, entry, parse(body)?.str("onConflict") ?: "fail")
            else -> error(r, 404, "not_found", "No route")
        }
    }

    private fun restorePreview(entry: TrashItem): JsonObject {
        val conflict = taken(entry.payload)
        val free = if (conflict) freeNumber(entry.payload) else null
        val share = if (entry.files.isEmpty()) 0 else entry.sizeBytes / entry.files.size
        return buildJsonObject {
            put("entryId", entry.id)
            put("reason", entry.reason)
            put("label", entry.label)
            put("conflict", conflict)
            put("items", JsonArray(entry.files.map { name ->
                buildJsonObject {
                    put("name", name)
                    put("size", share)
                    put("conflict", conflict)
                    put("freeName", if (!conflict) JsonPrimitive(name) else free?.let { JsonPrimitive(renamed(name, it)) } ?: JsonNull)
                    put("replaceName", JsonNull)
                }
            }))
            put("restoredBytes", entry.sizeBytes)
            put("freeNameUnavailable", if (conflict && free == null) JsonPrimitive("all-taken") else JsonNull)
            put("replaceable", false)
            put("replaceDisplaced", JsonArray(emptyList()))
            put("replaceKeptAs", JsonNull)
            put("replaceUnavailable", JsonPrimitive("not-a-save"))
        }
    }

    private fun restore(r: Request, entry: TrashItem, onConflict: String): Response {
        val payload = entry.payload
        val conflict = taken(payload)
        if (onConflict == "replace") {
            return error(r, 422, "unsupported_format", "Only the save of an existing game can replace the current one", buildJsonObject { put("reason", "not-a-save") })
        }
        var number: Int? = null
        if (conflict) {
            if (onConflict != "rename") {
                return error(r, 409, "conflict", "A file exists where the entry goes back", buildJsonObject { put("conflicts", JsonArray(entry.files.map(::JsonPrimitive))) })
            }
            number = freeNumber(payload) ?: return error(r, 409, "conflict", "No free name", buildJsonObject { put("freeNameUnavailable", "all-taken") })
        }
        val suffix = number?.let { " ($it)" } ?: ""
        when (payload) {
            is Payload.Game -> {
                payload.game.path = (if (payload.game.parent.isEmpty()) "" else payload.game.parent + "/") + payload.game.name + suffix + payload.game.extension
                payload.system.games += payload.game
                library(payload.system)
            }
            is Payload.Pak -> {
                paks += PakState(payload.pak.name + suffix, payload.pak.kind, payload.pak.sizeBytes, payload.pak.modifiedAt, payload.pak.version)
                emit("paks", JsonObject(emptyMap()))
                library(null)
            }
            is Payload.Backup -> {
                payload.game.backups.add(0, payload.backup)
                library(null)
            }
            is Payload.State -> {
                payload.game.slots[payload.slot] = payload.state
                library(null)
            }
            is Payload.Art -> {
                payload.game.art = payload.art
                library(null)
            }
            null -> Unit
        }
        trash.remove(entry)
        return json(r, 200, buildJsonObject {
            put("restored", JsonArray(entry.files.map { JsonPrimitive(renamed(it, number)) }))
            put("restoredBytes", entry.sizeBytes)
            put("renamed", number != null)
            put("replacedEntryId", JsonNull)
            put("replaced", JsonArray(emptyList()))
            put("replacedKeptAs", JsonNull)
        })
    }

    // MARK: events

    private fun openStream(r: Request): Response {
        val pipe = Pipe(1L shl 20)
        pipe.sink.timeout().timeout(2, TimeUnit.SECONDS)
        streams += pipe
        write(pipe, "hello", buildJsonObject { put("serverTime", time(nowMillis())); put("keepAliveSeconds", 15) })
        return response(r, 200, PipeBody(pipe)).newBuilder().header("Cache-Control", "no-store").build()
    }

    private class PipeBody(private val pipe: Pipe) : ResponseBody() {
        private val source = pipe.source.buffer()

        override fun contentType() = "text/event-stream; charset=utf-8".toMediaType()

        override fun contentLength() = -1L

        override fun source(): BufferedSource = source

        /** A blocked read ends at once (a pipe's source does not wake on close alone). */
        override fun close() {
            pipe.cancel()
        }
    }

    private fun write(pipe: Pipe, type: String, data: JsonElement): Boolean = try {
        val text = "id: ${nextEventId++}\nevent: $type\ndata: $data\n\n"
        val buffer = Buffer().writeUtf8(text)
        pipe.sink.write(buffer, buffer.size)
        pipe.sink.flush()
        true
    } catch (_: Exception) {
        false
    }

    private fun emit(type: String, data: JsonElement) {
        streams.removeAll { !write(it, type, data) }
    }

    private fun library(system: SystemState?) {
        emit("library", buildJsonObject { put("systemIds", JsonArray(listOfNotNull(system?.def?.id).map(::JsonPrimitive))) })
    }

    private fun keepAlive() = synchronized(lock) {
        streams.removeAll { pipe ->
            try {
                val buffer = Buffer().writeUtf8(": keep-alive\n\n")
                pipe.sink.write(buffer, buffer.size)
                pipe.sink.flush()
                false
            } catch (_: Exception) {
                true
            }
        }
    }

    /** Tests and the demo: ends the event streams as the console closing ReminisLink would (`shutdown`). */
    fun sendShutdown() = synchronized(lock) {
        streams.forEach { write(it, "shutdown", buildJsonObject { put("reason", "quit") }); runCatching { it.sink.close() } }
        streams.clear()
    }

    /** Tests: the number of open event streams. */
    val openStreams: Int get() = synchronized(lock) { streams.size }

    // MARK: responses

    private fun response(r: Request, code: Int, body: ResponseBody) = Response.Builder()
        .request(r).protocol(Protocol.HTTP_1_1).code(code).message(if (code < 400) "OK" else "Error").body(body).build()

    private fun json(r: Request, code: Int, value: JsonElement) = response(r, code, value.toString().toResponseBody(JSON))

    private fun empty(r: Request) = response(r, 204, ByteArray(0).toResponseBody(null))

    private fun error(r: Request, code: Int, errorCode: String, message: String, details: JsonObject? = null) = json(
        r, code,
        buildJsonObject {
            put("error", buildJsonObject {
                put("code", errorCode)
                put("message", message)
                put("details", details ?: JsonObject(emptyMap()))
            })
        },
    )

    private fun stream(r: Request, blob: Blob, type: String = "application/octet-stream"): Response {
        val body = object : ResponseBody() {
            private val source = blob.source().buffer()
            override fun contentType() = type.toMediaType()
            override fun contentLength() = blob.size
            override fun source() = source
        }
        return response(r, 200, body)
    }

    private fun parse(body: ByteArray): JsonObject? =
        runCatching { ProtocolJson.parseToJsonElement(body.toString(Charsets.UTF_8)) as? JsonObject }.getOrNull()

    private fun JsonObject.str(key: String): String = (this[key] as? JsonPrimitive)?.contentOrNull ?: ""

    private fun JsonPrimitive.long(): Long = longOrNull ?: 0

    private fun newId(prefix: String) = "${prefix}_${stamp(nowMillis())}_${"%04x".format(++counter)}"

    private fun stamp(millis: Long) = time(millis).replace("-", "").replace(":", "")

    private fun time(millis: Long): String = Instant.ofEpochSecond(millis / 1000).toString()

    /** Generated bytes of a file whose content is not kept (a deterministic pattern). */
    private class PatternSource(private var left: Long, seed: Int) : Source {
        private var value = seed

        override fun read(sink: Buffer, byteCount: Long): Long {
            if (left <= 0) return -1
            val n = minOf(left, byteCount, 64L * 1024).toInt()
            val bytes = ByteArray(n) { (value++ * 31 + 7).toByte() }
            sink.write(bytes)
            left -= n
            return n.toLong()
        }

        override fun timeout(): Timeout = Timeout.NONE

        override fun close() = Unit
    }

