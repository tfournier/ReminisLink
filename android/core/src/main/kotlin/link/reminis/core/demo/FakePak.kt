    private fun trashJson() = buildJsonObject {
        put("entries", JsonArray(trash.map { e ->
            buildJsonObject {
                put("id", e.id)
                put("trashedAt", time(e.trashedAt))
                put("reason", e.reason)
                put("label", e.label)
