    }

    private fun emptyTrash(r: Request): Response {
        if (r.header("X-RL-Confirm") != "empty-trash") return error(r, 400, "invalid_request", "Missing confirmation")
        val freed = trash.sumOf { it.sizeBytes }
        trash.clear()
        library(null)
        return json(r, 200, buildJsonObject { put("freedBytes", freed) })
    }

    /** Whether the place of a payload is taken; with [suffix], under that free name. */
    private fun taken(payload: Payload?, suffix: String = ""): Boolean = when (payload) {
        null -> true
        is Payload.Game -> payload.system.games.any {
            it.parent == payload.game.parent && it.fileName.equals(payload.game.name + suffix + payload.game.extension, ignoreCase = true)
        }
        is Payload.Pak -> paks.any { it.name.equals(payload.pak.name + suffix, ignoreCase = true) }
        is Payload.Backup -> suffix.isEmpty() && payload.game.backups.any { it.id == payload.backup.id }
        is Payload.State -> suffix.isEmpty() && payload.game.slots.containsKey(payload.slot)
        is Payload.Art -> suffix.isEmpty() && payload.game.art != null
        is Payload.Screenshots -> payload.shots.any { shot -> screenshotTaken(renamed(shot.name, suffix)) }
    }

    private fun freeNumber(payload: Payload?): Int? {
        if (payload !is Payload.Game && payload !is Payload.Pak && payload !is Payload.Screenshots) return null
        return (2..99).firstOrNull { !taken(payload, " ($it)") }
    }

    /** [name] with [suffix] (` (n)`) before its extension. */
    private fun renamed(name: String, suffix: String): String {
        if (suffix.isEmpty()) return name
        val dot = name.lastIndexOf('.').takeIf { it > 0 } ?: name.length
        return name.substring(0, dot) + suffix + name.substring(dot)
    }

    private fun renamed(name: String, number: Int?): String {
        if (number == null) return name
        val dot = name.lastIndexOf('.').takeIf { it > 0 } ?: name.length
        return name.substring(0, dot) + " ($number)" + name.substring(dot)
    }

    private fun trashRoute(r: Request, m: String, s: List<String>, body: ByteArray): Response {
        val entry = trash.firstOrNull { it.id == s[1] } ?: return error(r, 404, "not_found", "Trash entry not found")
        return when {
            m == "DELETE" && s.size == 2 -> {
                if (r.header("X-RL-Confirm") != "empty-trash") return error(r, 400, "invalid_request", "Missing confirmation")
                trash.remove(entry)
                library(null)
                json(r, 200, buildJsonObject { put("freedBytes", entry.sizeBytes) })
            }
            m == "GET" && s.size == 3 && s[2] == "restore" -> json(r, 200, restorePreview(entry))
            m == "POST" && s.size == 3 && s[2] == "restore" -> restore(r, entry, parse(body)?.str("onConflict") ?: "fail")
            else -> error(r, 404, "not_found", "No route")
        }
    }

    private fun restorePreview(entry: TrashItem): JsonObject {
        val conflict = taken(entry.payload)
        val free = if (conflict) freeNumber(entry.payload) else null
        val share = if (entry.files.isEmpty()) 0 else entry.sizeBytes / entry.files.size
        return buildJsonObject {
            put("entryId", entry.id)
            put("reason", entry.reason)
            put("label", entry.label)
            put("conflict", conflict)
            put("items", JsonArray(entry.files.map { name ->
                buildJsonObject {
                    put("name", name)
                    put("size", share)
                    put("conflict", conflict)
                    put("freeName", if (!conflict) JsonPrimitive(name) else free?.let { JsonPrimitive(renamed(name, it)) } ?: JsonNull)
                    put("replaceName", JsonNull)
                }
            }))
            put("restoredBytes", entry.sizeBytes)
            put("freeNameUnavailable", if (conflict && free == null) JsonPrimitive("all-taken") else JsonNull)
            put("replaceable", false)
            put("replaceDisplaced", JsonArray(emptyList()))
            put("replaceKeptAs", JsonNull)
            put("replaceUnavailable", JsonPrimitive("not-a-save"))
        }
    }

    private fun restore(r: Request, entry: TrashItem, onConflict: String): Response {
        val payload = entry.payload
        val conflict = taken(payload)
        if (onConflict == "replace") {
            return error(r, 422, "unsupported_format", "Only the save of an existing game can replace the current one", buildJsonObject { put("reason", "not-a-save") })
        }
        var number: Int? = null
        if (conflict) {
            if (onConflict != "rename") {
                return error(r, 409, "conflict", "A file exists where the entry goes back", buildJsonObject { put("conflicts", JsonArray(entry.files.map(::JsonPrimitive))) })
            }
            number = freeNumber(payload) ?: return error(r, 409, "conflict", "No free name", buildJsonObject { put("freeNameUnavailable", "all-taken") })
        }
        val suffix = number?.let { " ($it)" } ?: ""
        when (payload) {
            is Payload.Game -> {
                payload.game.path = (if (payload.game.parent.isEmpty()) "" else payload.game.parent + "/") + payload.game.name + suffix + payload.game.extension
                payload.system.games += payload.game
                library(payload.system)
            }
            is Payload.Pak -> {
                paks += PakState(payload.pak.name + suffix, payload.pak.kind, payload.pak.sizeBytes, payload.pak.modifiedAt, payload.pak.version)
                emit("paks", JsonObject(emptyMap()))
                library(null)
            }
            is Payload.Backup -> {
                payload.game.backups.add(0, payload.backup)
                library(null)
            }
            is Payload.State -> {
                payload.game.slots[payload.slot] = payload.state
                library(null)
            }
            is Payload.Art -> {
                payload.game.art = payload.art
                library(null)
            }
            is Payload.Screenshots -> {
                screenshots += payload.shots.map { it.renamed(renamed(it.name, suffix)) }
                emit("screenshots", JsonObject(emptyMap()))
            }
            null -> Unit
        }
        trash.remove(entry)
        return json(r, 200, buildJsonObject {
            put("restored", JsonArray(entry.files.map { JsonPrimitive(renamed(it, number)) }))
            put("restoredBytes", entry.sizeBytes)
            put("renamed", number != null)
            put("replacedEntryId", JsonNull)
            put("replaced", JsonArray(emptyList()))
            put("replacedKeptAs", JsonNull)
        })
    }

