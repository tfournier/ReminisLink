    private fun createUpload(r: Request, body: ByteArray): Response {
        val request = parse(body) ?: throw BadRequest("Invalid JSON")
        val target = request["target"] as? JsonObject ?: throw BadRequest("Missing target")
        val size = (request["sizeBytes"] as? JsonPrimitive)?.longOrNull ?: throw BadRequest("Missing sizeBytes")
        if (size < 0 || size > 4L shl 30) return error(r, 413, "too_large", "Too large")
        val upload = Upload(
            newId("up"), target, size, (request["onConflict"] as? JsonPrimitive)?.contentOrNull ?: "fail",
            if (size <= MAX_KEPT_BYTES) java.io.ByteArrayOutputStream(size.toInt()) else null,
        )
        uploads[upload.id] = upload
        return json(r, 201, buildJsonObject {
            put("uploadId", upload.id)
            put("chunkSize", CHUNK_SIZE)
            put("offset", 0)
            put("expiresAt", time(nowMillis() + 86_400_000))
        })
    }

    private fun uploadRoute(r: Request, m: String, s: List<String>, body: ByteArray): Response {
        val upload = uploads[s[1]] ?: return error(r, 404, "not_found", "Upload not found")
        return when {
            m == "GET" && s.size == 2 -> json(r, 200, buildJsonObject { put("uploadId", upload.id); put("offset", upload.offset); put("sizeBytes", upload.sizeBytes) })
            m == "DELETE" && s.size == 2 -> {
                uploads.remove(upload.id)
                empty(r)
            }
            m == "PUT" && s.size == 2 -> {
                val offset = r.header("Upload-Offset")?.toLongOrNull() ?: throw BadRequest("Missing Upload-Offset")
                if (offset != upload.offset || offset + body.size > upload.sizeBytes) {
                    error(r, 409, "conflict", "Offset mismatch", buildJsonObject { put("offset", upload.offset) })
                } else {
                    upload.data?.write(body)
                    upload.offset += body.size
                    response(r, 204, ByteArray(0).toResponseBody(null)).newBuilder().header("Upload-Offset", upload.offset.toString()).build()
                }
            }
            m == "POST" && s.size == 3 && s[2] == "complete" -> complete(r, upload)
            else -> error(r, 404, "not_found", "No route")
        }
    }

    private fun complete(r: Request, upload: Upload): Response {
        if (upload.offset != upload.sizeBytes) return error(r, 409, "conflict", "Upload incomplete", buildJsonObject { put("offset", upload.offset) })
        val blob = upload.data?.toByteArray()?.let { Blob.of(it) } ?: Blob(upload.sizeBytes, null, upload.id.hashCode())
        val t = upload.target
        val result = when (t.str("kind")) {
            "rom" -> {
                val system = systems.firstOrNull { it.def.id == t.str("systemId") } ?: return error(r, 404, "not_found", "System not found")
                val folderId = (t["folderId"] as? JsonPrimitive)?.contentOrNull
                val parent = folderId?.let { id ->
                    system.games.map { it.parent }.filter { it.isNotEmpty() }.firstOrNull { DemoLibrary.id(system.def.folder + "/" + it) == id }
                        ?: return error(r, 404, "not_found", "Folder not found")
                } ?: ""
                val wanted = cleanName(t.str("fileName")) ?: return error(r, 400, "invalid_name", "Invalid name")
                var name = wanted
                val existing = system.games.firstOrNull { it.parent == parent && it.fileName.equals(name, ignoreCase = true) }
                if (existing != null) {
                    when (upload.onConflict) {
                        "rename" -> {
                            val dot = wanted.lastIndexOf('.').takeIf { it > 0 } ?: wanted.length
                            var n = 2
                            while (system.games.any { it.parent == parent && it.fileName.equals(wanted.substring(0, dot) + " ($n)" + wanted.substring(dot), ignoreCase = true) }) n++
                            name = wanted.substring(0, dot) + " ($n)" + wanted.substring(dot)
                        }
                        "overwrite" -> {
                            trash.add(0, TrashItem(newId("tr"), nowMillis(), "overwrite", existing.name, listOf(existing.fileName), existing.rom.size, null))
                            system.games.remove(existing)
                        }
                        else -> return error(r, 409, "conflict", "A game of that name exists", buildJsonObject { put("existing", "Roms/${system.def.folder}/${existing.path}") })
                    }
                }
                val game = GameState(if (parent.isEmpty()) name else "$parent/$name", "file", blob, nowMillis(), null, nowMillis(), art = null)
                system.games += game
                library(system)
                buildJsonObject { put("gameId", gameId(system, game)) }
            }
            "save" -> {
                val (system, game) = find(t.str("gameId")) ?: return error(r, 404, "not_found", "Game not found")
                val backup = game.save?.let { addBackup(game, it, "Avant remplacement", "before-replace") }
                game.save = blob
                game.saveModifiedAt = nowMillis()
                library(system)
                buildJsonObject { put("backup", backup?.let(::backupJson) ?: JsonNull) }
            }
            "state" -> {
                val (system, game) = find(t.str("gameId")) ?: return error(r, 404, "not_found", "Game not found")
                val slot = (t["slot"] as? JsonPrimitive)?.intOrNull ?: throw BadRequest("Missing slot")
                val previous = game.slots[slot]
                if (previous?.lockCopy != null) return error(r, 409, "state_locked", "State is locked")
                if (previous != null) {
                    trash.add(0, TrashItem(newId("tr"), nowMillis(), "replace-state", "${game.name} – ${slot + 1}", listOf("${game.fileName}.st$slot"), previous.state.size, Payload.State(game, slot, previous)))
                }
                val st = SlotState(blob, nowMillis(), false, null)
                game.slots[slot] = st
                library(system)
                buildJsonObject { put("slot", slotJson(slot, st)) }
            }
            "staging" -> {
                val id = newId("st")
                staging[id] = t.str("fileName") to blob
                buildJsonObject { put("stagingId", id) }
            }
            "pak" -> {
                val fileName = t.str("fileName")
                val name = fileName.removeSuffix(".zip").removeSuffix(".ZIP").removeSuffix(".pak").ifBlank { "Demo Tool" }
                if (name.equals("ReminisLink", ignoreCase = true)) {
                    return error(r, 409, "conflict", "ReminisLink cannot delete or replace itself", buildJsonObject { put("self", true) })
                }
                val existing = paks.firstOrNull { it.name.equals(name, ignoreCase = true) }
                if (existing != null && upload.onConflict != "overwrite") {
                    return error(r, 409, "conflict", "Pak exists", buildJsonObject { put("existing", existing.path) })
                }
                val kind = if (t.str("pakKind") == "emu") "emu" else "tool"
                val job = startJob("pak-install") {
                    existing?.let {
                        paks.remove(it)
                        trash.add(0, TrashItem(newId("tr"), nowMillis(), "replace-pak", it.name, listOf(it.path), it.sizeBytes, Payload.Pak(it)))
                    }
                    val pak = PakState(name, kind, blob.size, nowMillis(), null)
                    paks += pak
                    emit("paks", JsonObject(emptyMap()))
                    buildJsonObject { put("pakId", pak.id) }
                }
                buildJsonObject { put("jobId", job.id) }
            }
            else -> throw BadRequest("Invalid target")
        }
        uploads.remove(upload.id)
        return json(r, 200, result)
    }

    private fun cleanName(name: String): String? {
        val trimmed = name.trim()
        if (trimmed.isEmpty() || trimmed == "." || trimmed == ".." || trimmed.any { it == '/' || it == '\\' || it < ' ' }) return null
        return java.text.Normalizer.normalize(trimmed, java.text.Normalizer.Form.NFC)
    }

