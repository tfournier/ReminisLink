    private fun addBackup(game: GameState, blob: Blob, label: String?, reason: String): BackupState {
        val now = nowMillis()
        val backup = BackupState("bk_${stamp(now)}_${"%04x".format(++counter)}", label, now, blob, reason)
        game.backups.add(0, backup)
        return backup
    }

    private fun saveRoute(r: Request, m: String, system: SystemState, game: GameState, rest: List<String>, body: ByteArray): Response = when {
        m == "GET" && rest.isEmpty() -> game.save?.let { stream(r, it) } ?: error(r, 404, "not_found", "No save")
        m == "PUT" && rest.isEmpty() -> {
            if (body.size > 64 shl 20) {
                error(r, 413, "too_large", "Body too large")
            } else {
                val previous = game.save
                val backup = previous?.let { addBackup(game, it, "Avant remplacement", "before-replace") }
                game.save = Blob.of(body)
                game.saveModifiedAt = nowMillis()
                library(system)
                json(r, 200, buildJsonObject { put("backup", backup?.let(::backupJson) ?: JsonNull) })
            }
        }
        m == "GET" && rest == listOf("backups") -> json(r, 200, buildJsonObject { put("backups", JsonArray(game.backups.map(::backupJson))) })
        m == "POST" && rest == listOf("backups") -> {
            val save = game.save
            if (save == null) {
                error(r, 404, "not_found", "No save")
            } else {
                val label = parse(body)?.get("label")?.let { (it as? JsonPrimitive)?.contentOrNull }
                if (label != null && label.codePointCount(0, label.length) > 80) {
                    error(r, 400, "invalid_request", "Label too long")
                } else {
                    val backup = addBackup(game, save, label?.trim()?.ifEmpty { null }, "manual")
                    library(system)
                    json(r, 201, backupJson(backup))
                }
            }
        }
        rest.size >= 2 && rest[0] == "backups" -> {
            val backup = game.backups.firstOrNull { it.id == rest[1] }
            when {
                backup == null -> error(r, 404, "not_found", "Backup not found")
                m == "GET" && rest.size == 2 -> stream(r, backup.blob)
                m == "DELETE" && rest.size == 2 -> {
                    game.backups.remove(backup)
                    trash.add(0, TrashItem(newId("tr"), nowMillis(), "delete-backup", backup.label ?: game.name, listOf("${game.fileName}.sav"), backup.blob.size, Payload.Backup(game, backup)))
                    library(system)
                    empty(r)
                }
                m == "POST" && rest.size == 3 && rest[2] == "restore" -> {
                    val kept = game.save?.let { addBackup(game, it, null, "before-restore") }
                    game.save = backup.blob
                    game.saveModifiedAt = nowMillis()
                    library(system)
                    json(r, 200, buildJsonObject { put("backup", kept?.let(::backupJson) ?: JsonNull) })
                }
                else -> error(r, 404, "not_found", "No route")
            }
        }
        else -> error(r, 404, "not_found", "No route")
    }

    // MARK: states

    private fun slotJson(slot: Int, st: SlotState) = buildJsonObject {
        put("slot", slot)
        put("sizeBytes", st.state.size)
        put("modifiedAt", time(st.modifiedAt))
        put("hasThumbnail", st.hasThumbnail)
        put("locked", st.lockCopy != null)
        val status = when {
            st.lockCopy == null -> null
            st.restoredPending -> "restored"
            st.forcedStatus != null -> st.forcedStatus
            else -> "intact"
        }
        put("lockStatus", status?.let(::JsonPrimitive) ?: JsonNull)
    }

    private fun stateRoute(r: Request, m: String, system: SystemState, game: GameState, rest: List<String>): Response {
        if (m == "GET" && rest.isEmpty()) {
            val list = game.slots.toSortedMap().map { (slot, st) -> slotJson(slot, st) }
            // `restored` is reported once.
            game.slots.values.forEach { it.restoredPending = false }
            return json(r, 200, buildJsonObject {
                put("slots", JsonArray(list))
                put("resumeSlot", game.resumeSlot?.let(::JsonPrimitive) ?: JsonNull)
            })
        }
        val slot = rest.firstOrNull()?.toIntOrNull() ?: return error(r, 400, "invalid_request", "Invalid slot")
        val st = game.slots[slot] ?: return error(r, 404, "not_found", "State not found")
        val action = rest.drop(1)
        return when {
            m == "GET" && action.isEmpty() -> stream(r, st.state)
            m == "GET" && action == listOf("thumbnail") ->
                if (st.hasThumbnail) stream(r, Blob.of(DemoArtwork.png(160, 120, slot * 5 + game.name.length)), "image/png") else error(r, 404, "not_found", "No thumbnail")
            m == "DELETE" && action.isEmpty() -> {
                if (st.lockCopy != null) return error(r, 409, "state_locked", "State is locked")
                game.slots.remove(slot)
                val item = TrashItem(newId("tr"), nowMillis(), "delete-state", "${game.name} – ${slot + 1}", listOf("${game.fileName}.st$slot"), st.state.size, Payload.State(game, slot, st))
                trash.add(0, item)
                library(system)
                json(r, 200, buildJsonObject { put("trashEntryId", item.id); put("moved", JsonArray(item.files.map(::JsonPrimitive))); put("movedBytes", item.sizeBytes) })
            }
            m == "PUT" && action == listOf("lock") -> {
                st.lockCopy = st.state
                st.forcedStatus = null
                library(system)
                json(r, 200, slotJson(slot, st))
            }
            m == "DELETE" && action == listOf("lock") -> {
                st.lockCopy = null
                st.forcedStatus = null
                library(system)
                json(r, 200, slotJson(slot, st))
            }
            m == "POST" && action == listOf("restore") -> {
                val copy = st.lockCopy ?: return error(r, 404, "not_found", "No locked copy")
                val restored = SlotState(copy, nowMillis(), st.hasThumbnail, copy)
                game.slots[slot] = restored
                library(system)
                json(r, 200, slotJson(slot, restored))
            }
            else -> error(r, 404, "not_found", "No route")
        }
    }

    // MARK: cheats

    private fun etag(game: GameState) = "\"demo-${game.cheatsRevision}\""

    private fun cheatsJson(game: GameState) = buildJsonObject {
        put("cheats", JsonArray(game.cheats.mapIndexed { i, c -> JsonObject(c + ("index" to JsonPrimitive(i))) }))
        put("etag", etag(game))
    }

    private fun cheatRoute(r: Request, m: String, system: SystemState, game: GameState, rest: List<String>, body: ByteArray): Response = when {
        m == "GET" && rest.isEmpty() -> json(r, 200, cheatsJson(game))
        m == "PUT" && rest.isEmpty() -> {
            if (r.header("If-Match") != etag(game)) {
                error(r, 412, "conflict", "The cheats changed")
            } else {
                val list = (parse(body)?.get("cheats") as? JsonArray) ?: throw BadRequest("Missing cheats")
                game.cheats = list.map { c ->
                    val o = c as? JsonObject ?: throw BadRequest("Invalid cheat")
                    if (o.str("description").isEmpty() && o.str("code").isEmpty()) throw BadRequest("Empty cheat")
                    JsonObject(o - "index")
                }.toMutableList()
                game.cheatsRevision++
                library(system)
                json(r, 200, cheatsJson(game))
            }
        }
        m == "POST" && rest == listOf("import") -> {
            val request = parse(body) ?: throw BadRequest("Invalid JSON")
            val mode = request.str("mode")
            // Every demo `.cht` holds two made-up cheats.
            val imported = (1..2).map { n ->
                buildJsonObject {
                    put("description", cheatName(game.cheats.size + n))
                    put("code", "%08X+%04X".format(0x0300_0000 + n * 16, n))
                    put("enabled", false)
                    put("extra", JsonObject(emptyMap()))
                }
            }
            if (mode == "replace") game.cheats = imported.toMutableList() else game.cheats.addAll(imported)
            game.cheatsRevision++
            library(system)
            json(r, 200, buildJsonObject { put("imported", imported.size); put("total", game.cheats.size) })
        }
        else -> error(r, 404, "not_found", "No route")
    }

