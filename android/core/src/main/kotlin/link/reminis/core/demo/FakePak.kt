/**
 * The fake pak of the demo mode (M16, docs/specs/09 and 10): a whole console
 * in memory, answering the routes the Android app uses, behind an OkHttp
 * [interceptor] that never calls the network (no DNS lookup, no socket).
 * Kotlin counterpart of `FakePak` of ReminisLinkDemo (iOS), with the same
 * invented console, systems, games, paks and texts; simplified: the console
 * applies every change at once, patches only copy or keep the ROM (no patch
 * format is read), and nothing is kept once the demo ends ([close]).
 *
 * Every write sends the matching event on the open `GET /events` streams
 * (`library`, `paks`, `job`), as the real pak does, so the screens refresh
 * the same way. File contents are kept in memory up to [MAX_KEPT_BYTES];
 * a larger file keeps its size only and is served as generated bytes.
 */
class FakePak(
    val deviceId: String = UUID.randomUUID().toString(),
    val deviceName: String,
    /** The name of the made-up cheat N (1-based), localized by the app: "Demo cheat N" / « Code de démo N ». */
    private val cheatName: (Int) -> String,
    private val nowMillis: () -> Long = System::currentTimeMillis,
) {
    private val lock = Any()
    private val executor: ScheduledExecutorService = Executors.newSingleThreadScheduledExecutor { r ->
        Thread(r, "demo-pak").apply { isDaemon = true }
    }

    @Volatile
    private var closed = false

    /** Answers every request of an [okhttp3.OkHttpClient] with the fake pak; never proceeds to the network. */
    val interceptor = Interceptor { chain -> handle(chain.request()) }

    // MARK: state

    private class Blob(val size: Long, val bytes: ByteArray?, val seed: Int) {
        fun source(): Source = if (bytes != null) Buffer().write(bytes) else PatternSource(size, seed)

        companion object {
            fun of(bytes: ByteArray, seed: Int = 0) =
                if (bytes.size <= MAX_KEPT_BYTES) Blob(bytes.size.toLong(), bytes, seed) else Blob(bytes.size.toLong(), null, seed)
        }
    }

    private class BackupState(val id: String, val label: String?, val createdAt: Long, val blob: Blob, val reason: String)

    private class SlotState(
        val state: Blob,
        val modifiedAt: Long,
        val hasThumbnail: Boolean,
        var lockCopy: Blob?,
        var restoredPending: Boolean = false,
        var forcedStatus: String? = null,
    )

    private class GameState(
        var path: String,
        val kind: String,
        var rom: Blob,
        var modifiedAt: Long,
        var save: Blob?,
        var saveModifiedAt: Long,
        val backups: MutableList<BackupState> = mutableListOf(),
        val slots: MutableMap<Int, SlotState> = mutableMapOf(),
        var resumeSlot: Int? = null,
        var cheats: MutableList<JsonObject> = mutableListOf(),
        var cheatsRevision: Int = 1,
        var art: Blob?,
    ) {
        val fileName: String get() = path.substringAfterLast('/')
        val name: String
            get() {
                if (kind.startsWith("folder")) return fileName
                val dot = fileName.lastIndexOf('.')
                return if (dot > 0) fileName.substring(0, dot) else fileName
            }
        val parent: String get() = if ('/' in path) path.substringBeforeLast('/') else ""
        val extension: String get() = if (kind.startsWith("folder")) "" else fileName.substring(name.length)
    }

    private class SystemState(val def: DemoLibrary.System, val games: MutableList<GameState>)

    private class PakState(val name: String, val kind: String, val sizeBytes: Long, val modifiedAt: Long, val version: String?, val isSelf: Boolean = false) {
        val id: String get() = Base64Url.encode("${if (kind == "emu") "Emus" else "Tools"}/tg5040/$name.pak".toByteArray())
        val path: String get() = "${if (kind == "emu") "Emus" else "Tools"}/tg5040/$name.pak"
    }

    private sealed interface Payload {
        class Game(val system: SystemState, val game: GameState, val keptSave: Boolean) : Payload
        class Pak(val pak: PakState) : Payload
        class Backup(val game: GameState, val backup: BackupState) : Payload
        class State(val game: GameState, val slot: Int, val state: SlotState) : Payload
        class Art(val game: GameState, val art: Blob) : Payload
        class Screenshots(val shots: List<ShotState>) : Payload
    }

    /** A screenshot of the fake console (M22). */
    private class ShotState(val name: String, val takenAt: Long, val gameName: String?, val sizeBytes: Long) {
        val id: String get() = "sc_" + Base64Url.encode(name.toByteArray(Charsets.UTF_8))
        val format: String
            get() = when (name.substringAfterLast('.', "").lowercase()) {
                "jpg", "jpeg" -> "jpeg"
                "bmp" -> "bmp"
                else -> "png"
            }

        fun renamed(name: String) = ShotState(name, takenAt, gameName, sizeBytes)
    }

    /** A job failed with this error (the `error` of the job). */
    private class JobFailed(val code: String, message: String, val details: JsonObject? = null) : Exception(message)

    private class TrashItem(
        val id: String,
        val trashedAt: Long,
        val reason: String,
        val label: String,
        val files: List<String>,
