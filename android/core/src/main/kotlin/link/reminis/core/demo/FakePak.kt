    private val uploads = mutableMapOf<String, Upload>()
    private val staging = mutableMapOf<String, Pair<String, Blob>>()
    private val screenshots = mutableListOf<ShotState>().apply { addAll(sampleScreenshots()) }
    private val jobs = mutableMapOf<String, JobState>()
    private val streams = mutableListOf<Pipe>()
    private var nextEventId = 1L
    private var counter = 0

    init {
        // A state replaced in game and a removed art wait in the trash, so the Trash screen is not empty.
        val first = systems[0].games[0]
        val slot = first.slots[1]
        if (slot != null) {
            trash += TrashItem(
                newId("tr"), BASE_MILLIS - 3_600_000, "delete-state", "${first.name} – 2",
                listOf("${first.name}.st1"), slot.state.size, null,
            )
        }
        executor.scheduleWithFixedDelay({ tick() }, 400, 400, TimeUnit.MILLISECONDS)
        executor.scheduleWithFixedDelay({ keepAlive() }, 15, 15, TimeUnit.SECONDS)
    }

    private fun seed(system: DemoLibrary.System, game: DemoLibrary.Game, index: Int): GameState {
        val base = game.modifiedAtSeconds * 1000
        val state = GameState(
            path = game.path, kind = game.kind, rom = Blob(game.sizeBytes, null, index + system.tag.hashCode()), modifiedAt = base,
            save = if (game.hasSave) Blob(131_072, null, 7 + index) else null, saveModifiedAt = base,
            art = if (game.hasArt) Blob.of(DemoArtwork.png(256, 256, index * 7 + system.tag.length)) else null,
        )
        if (game.hasSave) {
            state.backups += BackupState("bk_20261118T170000Z_a1b2", "Before the final boss", base - 3_600_000, Blob(131_072, null, 11), "manual")
            state.backups += BackupState("bk_20261117T090000Z_c3d4", null, base - 90_000_000, Blob(131_072, null, 12), "before-replace")
        }
        game.stateSlots.forEachIndexed { n, slot ->
            val blob = Blob(401_408, null, 20 + slot)
            val locked = n < game.lockedStateCount
            state.slots[slot] = SlotState(
                blob, base - n * 7_200_000L, n % 2 == 0, if (locked) blob else null,
                restoredPending = locked && n == 0, forcedStatus = if (locked && n == 1) "modified" else null,
            )
        }
        if (game.stateSlots.isNotEmpty()) {
            state.slots[RESUME_SLOT] = SlotState(Blob(401_408, null, 30), base, false, null)
            state.resumeSlot = RESUME_SLOT
        }
        state.cheats = (0 until game.cheatCount).map { i ->
            buildJsonObject {
                put("index", i)
                put("description", cheatName(i + 1))
                put("code", "%08X+%04X".format(0x0200_0000 + i * 16, i))
                put("enabled", i == 0)
                put("extra", if (i == 0) buildJsonObject { put("handler", "0") } else JsonObject(emptyMap()))
            }
        }.toMutableList()
        return state
    }

    /** Stops the timers and ends the open event streams. Nothing answers after this. */
    fun close() {
        closed = true
        executor.shutdownNow()
        synchronized(lock) {
            streams.forEach { runCatching { it.sink.close() } }
            streams.clear()
        }
    }

    // MARK: routing

    fun handle(request: Request): Response {
        if (closed) return error(request, 503, "shutting_down", "Shutting down")
        val segments = request.url.pathSegments
        if (segments.size < 2 || segments[0] != "api" || segments[1] != "v1") return error(request, 404, "not_found", "No route")
        val s = segments.drop(2)
        val body = request.body?.let { b -> Buffer().also { b.writeTo(it) }.readByteArray() } ?: ByteArray(0)
        val method = request.method
        return try {
            val response = synchronized(lock) { route(request, method, s, body) }
            // Tests: the console wrote the staging entry, its answer is held (outside the lock).
            if (method == "POST" && s.size == 3 && s[0] == "uploads" && s[2] == "complete") {
                completesAnswered.incrementAndGet()
                holdCompleteAnswer?.await(20, TimeUnit.SECONDS)
            }
            if (method == "POST" && s.size == 3 && s[0] == "archives" && s[2] == "import") {
                importsAnswered.incrementAndGet()
                holdImportAnswer?.await(20, TimeUnit.SECONDS)
            }
            response
        } catch (e: BadRequest) {
            error(request, 400, "invalid_request", e.message ?: "Invalid request")
        }
    }

    private class BadRequest(message: String) : Exception(message)

    /** Disconnected from the console ([disconnectClient]): every signed route answers `401 disconnected` but connect. */
    @Volatile
    var isClientDisconnected = false
        private set

    /**
     * Tests: as if the console disconnected this phone (Settings > Devices):
     * the open streams end without `shutdown` and every signed request gets
     * `401 disconnected` until `POST /clients/me/connect`.
     */
    fun disconnectClient() = synchronized(lock) {
        isClientDisconnected = true
        streams.forEach { runCatching { it.sink.close() } }
        streams.clear()
    }

    /** Tests: `GET /events` requests received (accepted or refused). */
    val eventsRequests = java.util.concurrent.atomic.AtomicInteger()

    /** Tests: when the last `GET /events` arrived (System.nanoTime). */
    val lastEventsRequestNanos = java.util.concurrent.atomic.AtomicLong()

    private fun countEvents(): Int {
        lastEventsRequestNanos.set(System.nanoTime())
        return eventsRequests.incrementAndGet()
    }

    /** Tests: `POST /clients/me/connect` requests received. */
    val connectRequests = java.util.concurrent.atomic.AtomicInteger()

    /** Tests: the next `GET /device` answers `401 disconnected` (the client is not disconnected otherwise). */
    @Volatile
    var failNextDeviceWithDisconnected = false

    /** Tests: ends the open streams without `shutdown` (the app probes, then reconnects). */
    fun dropStreams() = synchronized(lock) {
        streams.forEach { runCatching { it.sink.close() } }
        streams.clear()
    }

    private fun route(r: Request, m: String, s: List<String>, body: ByteArray): Response = when {
        m == "GET" && s == listOf("hello") -> json(r, 200, hello())
        m == "POST" && s == listOf("clients", "me", "connect") -> {
            connectRequests.incrementAndGet()
            isClientDisconnected = false
            empty(r)
        }
        m == "GET" && s == listOf("events") && countEvents() < 0 -> error(r, 500, "internal", "unreachable")
        isClientDisconnected -> error(r, 401, "disconnected", "Disconnected by the console")
        m == "GET" && s == listOf("device") && failNextDeviceWithDisconnected -> {
            failNextDeviceWithDisconnected = false
            error(r, 401, "disconnected", "Disconnected by the console")
        }
        m == "GET" && s == listOf("device") -> json(r, 200, device())
        m == "DELETE" && s == listOf("clients", "me") -> empty(r)
        m == "GET" && s == listOf("events") -> openStream(r)
        m == "GET" && s == listOf("systems") -> json(r, 200, systemsJson())
        m == "GET" && s == listOf("games") -> json(r, 200, allGames())
        s.size >= 2 && s[0] == "games" -> gameRoute(r, m, s, body)
        m == "POST" && s == listOf("uploads") -> createUpload(r, body)
        s.size >= 2 && s[0] == "uploads" -> uploadRoute(r, m, s, body)
        m == "GET" && s == listOf("jobs") -> json(r, 200, buildJsonObject { put("jobs", JsonArray(jobs.values.map(::jobJson))) })
        s.size == 2 && s[0] == "jobs" -> jobRoute(r, m, s[1])
        m == "GET" && s == listOf("paks") -> json(r, 200, buildJsonObject { put("paks", JsonArray(paks.map(::pakJson))) })
        m == "DELETE" && s.size == 2 && s[0] == "paks" -> deletePak(r, s[1])
        m == "GET" && s == listOf("sd", "files") -> sdFiles(r)
        m == "GET" && s == listOf("trash") -> json(r, 200, trashJson())
        m == "DELETE" && s == listOf("trash") -> emptyTrash(r)
        s.size >= 2 && s[0] == "trash" -> trashRoute(r, m, s, body)
        s.size >= 2 && s[0] == "archives" -> archiveRoute(r, m, s, body)
        s.isNotEmpty() && s[0] == "screenshots" -> screenshotRoute(r, m, s, body)
        else -> error(r, 404, "not_found", "No route")
    }

