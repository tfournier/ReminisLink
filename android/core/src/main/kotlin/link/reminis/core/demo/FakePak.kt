    }

    private fun artJson(system: SystemState, game: GameState) = buildJsonObject {
        put("id", gameId(system, game))
        put("name", game.name)
        put("hasArt", game.art != null)
    }

    private fun deletionItems(game: GameState, keepSave: Boolean): Pair<List<JsonObject>, List<JsonObject>> {
        fun item(name: String, role: String, size: Long) = buildJsonObject { put("name", name); put("role", role); put("size", size) }
        val data = buildList {
            game.save?.let { add(item("${game.fileName}.sav", "save", it.size)) }
            game.slots.filter { it.key != game.resumeSlot }.forEach { (slot, st) -> add(item("${game.fileName}.st$slot", "state", st.state.size)) }
        }
        val always = buildList {
            add(item(game.fileName, "rom", game.rom.size))
            if (game.cheats.isNotEmpty()) add(item("${game.fileName}.cht", "cheats", game.cheats.size * 64L))
            game.art?.let { add(item("${game.name}.png", "art", it.size)) }
        }
        return if (keepSave) always to data else (always + data) to emptyList()
    }

    private fun deletionPreview(system: SystemState, game: GameState, keepSave: Boolean): JsonObject {
        val (moved, kept) = deletionItems(game, keepSave)
        return buildJsonObject {
            put("moved", JsonArray(moved))
            put("kept", JsonArray(kept))
            put("movedBytes", moved.sumOf { (it["size"] as JsonPrimitive).long() })
        }
    }

    private fun deleteGame(r: Request, system: SystemState, game: GameState, keepSave: Boolean): Response {
        val (moved, _) = deletionItems(game, keepSave)
        val size = moved.sumOf { (it["size"] as JsonPrimitive).long() }
        val item = TrashItem(newId("tr"), nowMillis(), "delete-game", game.name, moved.map { it.str("name") }, size, Payload.Game(system, game, keepSave))
        trash.add(0, item)
        system.games.remove(game)
        library(system)
        return json(r, 200, buildJsonObject {
            put("trashEntryId", item.id)
            put("moved", JsonArray(item.files.map(::JsonPrimitive)))
            put("movedBytes", size)
        })
    }

