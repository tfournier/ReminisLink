    private fun slotJson(slot: Int, st: SlotState) = buildJsonObject {
        put("slot", slot)
        put("sizeBytes", st.state.size)
        put("modifiedAt", time(st.modifiedAt))
        put("hasThumbnail", st.hasThumbnail)
        put("locked", st.lockCopy != null)
        val status = when {
            st.lockCopy == null -> null
            st.restoredPending -> "restored"
            st.forcedStatus != null -> st.forcedStatus
            else -> "intact"
        }
        put("lockStatus", status?.let(::JsonPrimitive) ?: JsonNull)
    }

    private fun stateRoute(r: Request, m: String, system: SystemState, game: GameState, rest: List<String>): Response {
        if (m == "GET" && rest.isEmpty()) {
            val list = game.slots.toSortedMap().map { (slot, st) -> slotJson(slot, st) }
            // `restored` is reported once.
            game.slots.values.forEach { it.restoredPending = false }
            return json(r, 200, buildJsonObject {
                put("slots", JsonArray(list))
                put("resumeSlot", game.resumeSlot?.let(::JsonPrimitive) ?: JsonNull)
            })
        }
        val slot = rest.firstOrNull()?.toIntOrNull() ?: return error(r, 400, "invalid_request", "Invalid slot")
        val st = game.slots[slot] ?: return error(r, 404, "not_found", "State not found")
        val action = rest.drop(1)
        return when {
            m == "GET" && action.isEmpty() -> stream(r, st.state)
            m == "GET" && action == listOf("thumbnail") ->
                if (st.hasThumbnail) stream(r, Blob.of(DemoArtwork.png(160, 120, slot * 5 + game.name.length)), "image/png") else error(r, 404, "not_found", "No thumbnail")
            m == "DELETE" && action.isEmpty() -> {
                if (st.lockCopy != null) return error(r, 409, "state_locked", "State is locked")
                game.slots.remove(slot)
                val item = TrashItem(newId("tr"), nowMillis(), "delete-state", "${game.name} – ${slot + 1}", listOf("${game.fileName}.st$slot"), st.state.size, Payload.State(game, slot, st))
                trash.add(0, item)
                library(system)
                json(r, 200, buildJsonObject { put("trashEntryId", item.id); put("moved", JsonArray(item.files.map(::JsonPrimitive))); put("movedBytes", item.sizeBytes) })
            }
            m == "PUT" && action == listOf("lock") -> {
                st.lockCopy = st.state
                st.forcedStatus = null
                library(system)
                json(r, 200, slotJson(slot, st))
            }
            m == "DELETE" && action == listOf("lock") -> {
                st.lockCopy = null
                st.forcedStatus = null
                library(system)
                json(r, 200, slotJson(slot, st))
            }
            m == "POST" && action == listOf("restore") -> {
                val copy = st.lockCopy ?: return error(r, 404, "not_found", "No locked copy")
                val restored = SlotState(copy, nowMillis(), st.hasThumbnail, copy)
                game.slots[slot] = restored
                library(system)
                json(r, 200, slotJson(slot, restored))
            }
            else -> error(r, 404, "not_found", "No route")
        }
    }

