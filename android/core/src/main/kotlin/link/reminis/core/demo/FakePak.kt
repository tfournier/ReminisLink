    private fun screenshotRoute(r: Request, m: String, s: List<String>, body: ByteArray): Response {
        if (!screenshotsSupported) return error(r, 404, "not_found", "No route")
        return when {
            m == "GET" && s.size == 1 -> json(r, 200, screenshotList())
            m == "POST" && s == listOf("screenshots", "trash") -> {
                val ids = (parse(body)?.get("screenshotIds") as? JsonArray)?.mapNotNull { (it as? JsonPrimitive)?.contentOrNull }
                if (ids == null || ids.size !in 1..500) return error(r, 400, "invalid_request", "screenshotIds must hold 1 to 500 identifiers")
                if (ids.any { !it.startsWith("sc_") || Base64Url.decode(it.removePrefix("sc_")) == null }) {
                    return error(r, 400, "invalid_id", "Invalid identifier")
                }
                val unique = ids.distinct()
                val missing = unique.filter { id -> screenshots.none { it.id == id } }
                if (missing.isNotEmpty()) {
                    return error(r, 404, "not_found", "Screenshot not found", buildJsonObject { put("missing", JsonArray(missing.map(::JsonPrimitive))) })
                }
                val moved = moveScreenshots(unique)
                if (failNextScreenshotTrash) {
                    failNextScreenshotTrash = false
                    return error(r, 500, "internal", "Internal error", buildJsonObject {
                        put("kept", JsonArray(unique.map(::JsonPrimitive)))
                        put("held", 0)
                        put("trashEntryId", moved.str("trashEntryId"))
                    })
                }
                json(r, 200, moved)
            }
            m == "GET" && s.size == 2 -> screenshotContent(r, s[1], thumbnail = false)
            m == "GET" && s.size == 3 && s[2] == "thumbnail" -> screenshotContent(r, s[1], thumbnail = true)
            else -> error(r, 404, "not_found", "No route")
        }
    }

    private fun screenshotList() = buildJsonObject {
        val shots = sortedScreenshots()
        put("screenshots", JsonArray(shots.map { shot ->
            buildJsonObject {
                put("screenshotId", shot.id)
                put("name", shot.name)
                put("takenAt", time(shot.takenAt))
                put("sizeBytes", shot.sizeBytes)
                put("format", shot.format)
                put("gameName", shot.gameName?.let(::JsonPrimitive) ?: JsonNull)
                put("hasThumbnail", shot.format != "bmp")
                put("futureField", "ignored by the app")
            }
        }))
        put("totalBytes", shots.sumOf { it.sizeBytes })
        put("truncated", false)
    }

    private fun screenshotContent(r: Request, id: String, thumbnail: Boolean): Response {
        val shot = screenshots.firstOrNull { it.id == id } ?: return if (!id.startsWith("sc_") || Base64Url.decode(id.removePrefix("sc_")) == null) {
            error(r, 400, "invalid_id", "Invalid identifier")
        } else {
            error(r, 404, "not_found", "Screenshot not found")
        }
        if (thumbnail && shot.format == "bmp") return error(r, 404, "not_found", "Screenshot not found")
        val seed = (shot.gameName ?: shot.name).hashCode() + (shot.takenAt / 1000 % 997).toInt()
        val key = "${shot.name}#$thumbnail"
        val png = drawnScreens.getOrPut(key) { if (thumbnail) DemoArtwork.png(320, 240, seed) else DemoArtwork.png(640, 480, seed) }
        val response = stream(r, Blob.of(png), "image/png")
        if (thumbnail) return response
        val name = shot.name.replace("\"", "\\\"")
        return response.newBuilder().header("Content-Disposition", "attachment; filename=\"$name\"").build()
    }

    /** Moves screenshots to the trash in one entry (lock held); the `screenshots` event follows. */
    private fun moveScreenshots(ids: List<String>): JsonObject {
        val moved = ids.mapNotNull { id -> screenshots.firstOrNull { it.id == id } }
        if (moved.isEmpty()) return buildJsonObject { put("trashEntryId", ""); put("moved", JsonArray(emptyList())); put("movedBytes", 0) }
        screenshots.removeAll(moved.toSet())
        val files = moved.map { "Screenshots/${it.name}" }
        val bytes = moved.sumOf { it.sizeBytes }
        val item = TrashItem(
            newId("tr"), nowMillis(), "delete-screenshot", if (moved.size == 1) moved[0].name else "${moved.size} screenshots",
            files, bytes, Payload.Screenshots(moved),
        )
        trash.add(0, item)
        emit("screenshots", JsonObject(emptyMap()))
        return buildJsonObject {
            put("trashEntryId", item.id)
            put("moved", JsonArray(files.map(::JsonPrimitive)))
            put("movedBytes", bytes)
        }
    }


    // MARK: events

    private fun openStream(r: Request): Response {
        val pipe = Pipe(1L shl 20)
        pipe.sink.timeout().timeout(2, TimeUnit.SECONDS)
        streams += pipe
        write(pipe, "hello", buildJsonObject { put("serverTime", time(nowMillis())); put("keepAliveSeconds", 15) })
        return response(r, 200, PipeBody(pipe)).newBuilder().header("Cache-Control", "no-store").build()
    }

    private class PipeBody(private val pipe: Pipe) : ResponseBody() {
        private val source = pipe.source.buffer()

        override fun contentType() = "text/event-stream; charset=utf-8".toMediaType()

        override fun contentLength() = -1L

        override fun source(): BufferedSource = source

        /** A blocked read ends at once (a pipe's source does not wake on close alone). */
        override fun close() {
            pipe.cancel()
        }
    }

    private fun write(pipe: Pipe, type: String, data: JsonElement): Boolean = try {
        val text = "id: ${nextEventId++}\nevent: $type\ndata: $data\n\n"
        val buffer = Buffer().writeUtf8(text)
        pipe.sink.write(buffer, buffer.size)
        pipe.sink.flush()
        true
    } catch (_: Exception) {
        false
    }

    private fun emit(type: String, data: JsonElement) {
        streams.removeAll { !write(it, type, data) }
    }

    private fun library(system: SystemState?) {
        emit("library", buildJsonObject { put("systemIds", JsonArray(listOfNotNull(system?.def?.id).map(::JsonPrimitive))) })
    }

    private fun keepAlive() = synchronized(lock) {
        streams.removeAll { pipe ->
            try {
                val buffer = Buffer().writeUtf8(": keep-alive\n\n")
                pipe.sink.write(buffer, buffer.size)
                pipe.sink.flush()
                false
            } catch (_: Exception) {
                true
            }
        }
    }

    /** Tests and the demo: ends the event streams as the console closing ReminisLink would (`shutdown`). */
    fun sendShutdown() = synchronized(lock) {
        streams.forEach { write(it, "shutdown", buildJsonObject { put("reason", "quit") }); runCatching { it.sink.close() } }
        streams.clear()
    }

    /** Tests: the number of open event streams. */
    val openStreams: Int get() = synchronized(lock) { streams.size }

    // MARK: responses

    private fun response(r: Request, code: Int, body: ResponseBody) = Response.Builder()
        .request(r).protocol(Protocol.HTTP_1_1).code(code).message(if (code < 400) "OK" else "Error").body(body).build()

    private fun json(r: Request, code: Int, value: JsonElement) = response(r, code, value.toString().toResponseBody(JSON))

    private fun empty(r: Request) = response(r, 204, ByteArray(0).toResponseBody(null))

    private fun error(r: Request, code: Int, errorCode: String, message: String, details: JsonObject? = null) = json(
        r, code,
        buildJsonObject {
            put("error", buildJsonObject {
                put("code", errorCode)
                put("message", message)
                put("details", details ?: JsonObject(emptyMap()))
            })
        },
    )

    private fun stream(r: Request, blob: Blob, type: String = "application/octet-stream"): Response {
        val body = object : ResponseBody() {
            private val source = blob.source().buffer()
            override fun contentType() = type.toMediaType()
            override fun contentLength() = blob.size
            override fun source() = source
        }
        return response(r, 200, body)
    }

    private fun parse(body: ByteArray): JsonObject? =
        runCatching { ProtocolJson.parseToJsonElement(body.toString(Charsets.UTF_8)) as? JsonObject }.getOrNull()

    private fun JsonObject.str(key: String): String = (this[key] as? JsonPrimitive)?.contentOrNull ?: ""

    private fun JsonPrimitive.long(): Long = longOrNull ?: 0

    private fun newId(prefix: String) = "${prefix}_${stamp(nowMillis())}_${"%04x".format(++counter)}"

    private fun stamp(millis: Long) = time(millis).replace("-", "").replace(":", "")

    private fun time(millis: Long): String = Instant.ofEpochSecond(millis / 1000).toString()

    /** Generated bytes of a file whose content is not kept (a deterministic pattern). */
    private class PatternSource(private var left: Long, seed: Int) : Source {
        private var value = seed

        override fun read(sink: Buffer, byteCount: Long): Long {
            if (left <= 0) return -1
            val n = minOf(left, byteCount, 64L * 1024).toInt()
            val bytes = ByteArray(n) { (value++ * 31 + 7).toByte() }
            sink.write(bytes)
            left -= n
            return n.toLong()
        }

        override fun timeout(): Timeout = Timeout.NONE

        override fun close() = Unit
    }

