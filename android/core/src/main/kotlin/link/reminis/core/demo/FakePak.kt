    private fun gameId(system: SystemState, game: GameState) = DemoLibrary.id(system.def.folder + "/" + game.path)

    private fun find(gameId: String): Pair<SystemState, GameState>? {
        for (system in systems) for (game in system.games) if (gameId(system, game) == gameId) return system to game
        return null
    }

    private fun lockedCount(game: GameState) = game.slots.filter { it.key != game.resumeSlot && it.value.lockCopy != null }.size

    private fun summary(system: SystemState, game: GameState) = buildJsonObject {
        put("id", gameId(system, game))
        put("name", game.name)
        put("fileName", game.fileName)
        put("kind", game.kind)
        put("sizeBytes", game.rom.size)
        put("modifiedAt", time(game.modifiedAt))
        put("hasSave", game.save != null)
        put("stateCount", game.slots.keys.count { it != game.resumeSlot })
        put("lockedStateCount", lockedCount(game))
        put("cheatCount", game.cheats.size)
        put("hasArt", game.art != null)
        put("systemId", system.def.id)
        if (game.parent.isEmpty()) {
            put("folderId", JsonNull)
            put("folderPath", JsonNull)
        } else {
            put("folderId", DemoLibrary.id(system.def.folder + "/" + game.parent))
            put("folderPath", game.parent)
        }
    }

    private fun allGames() = buildJsonObject {
        put("games", JsonArray(systems.flatMap { s -> s.games.sortedBy { it.path.lowercase() }.map { summary(s, it) } }))
        put("truncated", false)
        put("generatedAt", time(nowMillis()))
    }

    private fun fileId(role: String, slot: Int? = null) = Base64Url.encode((if (slot == null) role else "$role-$slot").toByteArray())

    private fun files(system: SystemState, game: GameState) = buildJsonArray {
        fun file(role: String, path: String, blob: Blob, modified: Long, slot: Int? = null) = add(buildJsonObject {
            put("fileId", fileId(role, slot))
            put("role", role)
            if (slot != null) put("slot", slot)
            put("path", path)
            put("sizeBytes", blob.size)
            put("modifiedAt", time(modified))
        })
        val romPath = if (game.kind.startsWith("folder")) "Roms/${system.def.folder}/${game.path}/${game.name}.m3u" else "Roms/${system.def.folder}/${game.path}"
        file("rom", romPath, game.rom, game.modifiedAt)
        game.save?.let { file("save", "Saves/${system.def.tag}/${game.fileName}.sav", it, game.saveModifiedAt) }
        for ((slot, state) in game.slots.toSortedMap()) {
            if (slot == game.resumeSlot) continue
            file("state", ".userdata/shared/${system.def.tag}-demo/${game.fileName}.st$slot", state.state, state.modifiedAt, slot)
        }
        if (game.cheats.isNotEmpty()) {
            file("cheats", "Cheats/${system.def.tag}/${game.fileName}.cht", Blob(game.cheats.size * 64L, null, 3), game.modifiedAt)
        }
        game.art?.let { file("art", "Roms/${system.def.folder}/.media/${game.name}.png", it, game.modifiedAt) }
    }

    private fun detail(system: SystemState, game: GameState): JsonObject {
        val files = files(system, game)
        return buildJsonObject {
            put("id", gameId(system, game))
            put("systemId", system.def.id)
            put("name", game.name)
            put("fileName", game.fileName)
            put("kind", game.kind)
            put("files", files)
            put("totalBytes", files.sumOf { (it.jsonObject["sizeBytes"] as JsonPrimitive).longOrNull ?: 0 })
        }
    }

    // MARK: games

    private fun gameRoute(r: Request, m: String, s: List<String>, body: ByteArray): Response {
        val (system, game) = find(s[1]) ?: return error(r, 404, "not_found", "Game not found")
        val rest = s.drop(2)
        return when {
            m == "GET" && rest.isEmpty() -> json(r, 200, detail(system, game))
            m == "DELETE" && rest.isEmpty() -> deleteGame(r, system, game, r.url.queryParameter("keepSave") == "true")
            m == "GET" && rest == listOf("deletion") -> json(r, 200, deletionPreview(system, game, r.url.queryParameter("keepSave") == "true"))
            m == "GET" && rest.size == 2 && rest[0] == "files" -> fileDownload(r, system, game, rest[1])
            m == "GET" && rest == listOf("art") -> game.art?.let { stream(r, it, "image/png") } ?: error(r, 404, "not_found", "No art")
            m == "PUT" && rest == listOf("art") -> setArt(r, system, game, body)
            m == "DELETE" && rest == listOf("art") -> removeArt(r, system, game)
            rest.firstOrNull() == "save" -> saveRoute(r, m, system, game, rest.drop(1), body)
            rest.firstOrNull() == "states" -> stateRoute(r, m, system, game, rest.drop(1))
            rest.firstOrNull() == "cheats" -> cheatRoute(r, m, system, game, rest.drop(1), body)
            m == "POST" && rest == listOf("patch") -> patch(r, system, game, body)
            m == "GET" && rest == listOf("archive") -> exportArchive(r, system, game)
            else -> error(r, 404, "not_found", "No route")
        }
    }

    private fun fileDownload(r: Request, system: SystemState, game: GameState, fileId: String): Response {
        val token = Base64Url.decode(fileId)?.toString(Charsets.UTF_8) ?: return error(r, 400, "invalid_id", "Invalid id")
        val blob = when {
            token == "rom" -> game.rom
            token == "save" -> game.save
            token == "art" -> game.art
            token == "cheats" -> Blob.of(cheatFile(game))
            token.startsWith("state-") -> token.removePrefix("state-").toIntOrNull()?.let { game.slots[it]?.state }
            else -> null
        } ?: return error(r, 404, "not_found", "File not found")
        return stream(r, blob)
    }

    private fun cheatFile(game: GameState): ByteArray = buildString {
        append("cheats = ${game.cheats.size}\n\n")
        game.cheats.forEachIndexed { i, c ->
            append("cheat${i}_desc = \"${c.str("description")}\"\n")
            append("cheat${i}_code = \"${c.str("code")}\"\n")
            append("cheat${i}_enable = ${(c["enabled"] as? JsonPrimitive)?.booleanOrNull == true}\n\n")
        }
    }.toByteArray()

    private fun setArt(r: Request, system: SystemState, game: GameState, body: ByteArray): Response {
        if (body.size > 4 shl 20) return error(r, 413, "too_large", "Art too large")
        if (body.size < 8 || !body.copyOfRange(0, 8).contentEquals(PNG_SIGNATURE)) return error(r, 422, "unsupported_format", "Not a PNG")
        game.art?.let { trash += TrashItem(newId("tr"), nowMillis(), "replace-art", game.name, listOf("${game.name}.png"), it.size, Payload.Art(game, it)) }
        game.art = Blob.of(body)
        library(system)
        return json(r, 200, artJson(system, game))
    }

    private fun removeArt(r: Request, system: SystemState, game: GameState): Response {
        val art = game.art ?: return error(r, 404, "not_found", "No art")
        trash += TrashItem(newId("tr"), nowMillis(), "delete-art", game.name, listOf("${game.name}.png"), art.size, Payload.Art(game, art))
        game.art = null
        library(system)
