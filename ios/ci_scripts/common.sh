# Shared by the Xcode Cloud scripts of ReminisLink (milestone M17). Sourced
# by bash; never prints a key or a token.
#
# App tags: ios-vX.Y.Z (release: App Store) and ios-beta-vX.Y.Z-beta.N or
# ios-beta-vX.Y.Z-rc.N (pre-release: TestFlight only). The two prefixes do not
# overlap: Xcode Cloud tag conditions are prefixes only, so "ios-v" starts the
# Release workflow and "ios-beta-v" the Beta workflow, never both for one tag
# (the checks below stay as a second guard). MARKETING_VERSION is X.Y.Z
# (the App Store takes three numbers, no suffix); CURRENT_PROJECT_VERSION is
# Xcode Cloud's build number. Both go into Config/CI.xcconfig (generated,
# ignored by Git, included by Config/Config.xcconfig): the Xcode project is
# never changed.
#
# Xcode Cloud workflows (ios/README.md, "Release"), told apart by their name
# (CI_WORKFLOW):
#   Release  ios-vX.Y.Z only: refuses a pre-release tag, so a beta never goes
#            to App Review.
#   Beta     ios-beta-vX.Y.Z-beta.N / -rc.N only.
#   Submit   optional: submits the processed build of ios-vX.Y.Z to App
#            Review (App Store Connect API); does nothing for a pre-release.
# Any other workflow (e.g. tests on pull requests) only gets the build number.

RL_CI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RL_IOS_DIR="$(cd "$RL_CI_DIR/.." && pwd)"
RL_CHANGELOG="${RL_CHANGELOG:-$RL_IOS_DIR/CHANGELOG.md}"
RL_CI_XCCONFIG="${RL_CI_XCCONFIG:-$RL_IOS_DIR/Config/CI.xcconfig}"
RL_RELEASE_WORKFLOW="${RL_RELEASE_WORKFLOW:-Release}"
RL_BETA_WORKFLOW="${RL_BETA_WORKFLOW:-Beta}"
RL_SUBMIT_WORKFLOW="${RL_SUBMIT_WORKFLOW:-Submit}"

rl_log() { printf 'ReminisLink: %s\n' "$*"; }
rl_fail() {
	printf 'ReminisLink: error: %s\n' "$*" >&2
	exit 1
}

# rl_parse_tag <tag>: sets RL_VERSION (X.Y.Z), RL_SUFFIX (beta.N, rc.N or
# empty) and RL_KIND (release or beta). Returns 1 for anything else.
rl_parse_tag() {
	local n='(0|[1-9][0-9]*)'
	local release="^ios-v$n\\.$n\\.$n\$"
	local beta="^ios-beta-v$n\\.$n\\.$n-((beta|rc)\\.$n)\$"
	RL_VERSION=""
	RL_SUFFIX=""
	RL_KIND=""
	if [[ "$1" =~ $release ]]; then
		RL_KIND=release
	elif [[ "$1" =~ $beta ]]; then
		RL_KIND=beta
		RL_SUFFIX="${BASH_REMATCH[4]}"
	else
		return 1
	fi
	RL_VERSION="${BASH_REMATCH[1]}.${BASH_REMATCH[2]}.${BASH_REMATCH[3]}"
}

# rl_tag_name <name>: prints the app tag for a "make" target name, which
# may give a pre-release as ios-vX.Y.Z-beta.N (written ios-beta-vX.Y.Z-beta.N)
# or directly as ios-beta-vX.Y.Z-beta.N. Returns 1 if neither is a valid tag.
rl_tag_name() {
	if rl_parse_tag "$1"; then
		printf '%s\n' "$1"
	elif [[ "$1" == ios-v* ]] && rl_parse_tag "ios-beta-v${1#ios-v}"; then
		printf '%s\n' "ios-beta-v${1#ios-v}"
	else
		return 1
	fi
}

# rl_has_changelog_section <X.Y.Z>: whether ios/CHANGELOG.md has "## X.Y.Z".
rl_has_changelog_section() {
	"$RL_CI_DIR/release_notes.sh" has "$1"
}

# rl_configure: checks CI_TAG, CI_WORKFLOW and CI_BUILD_NUMBER and writes
# Config/CI.xcconfig. Exits 1 (the build fails at once) when the tag is
# malformed or does not fit the workflow.
rl_configure() {
	local tag="${CI_TAG:-}" workflow="${CI_WORKFLOW:-}" build="${CI_BUILD_NUMBER:-}"
	RL_VERSION=""
	RL_SUFFIX=""
	RL_KIND=""
	if [ -n "$tag" ]; then
		rl_parse_tag "$tag" || rl_fail "malformed app tag '$tag': expected ios-vX.Y.Z, ios-beta-vX.Y.Z-beta.N or ios-beta-vX.Y.Z-rc.N"
		# A tag is a delivery: its workflow and build number must be known
		# (the local build number would collide with an earlier upload).
		case "$workflow" in
		"$RL_RELEASE_WORKFLOW" | "$RL_BETA_WORKFLOW" | "$RL_SUBMIT_WORKFLOW") ;;
		*) rl_fail "tag $tag in workflow '${workflow:-(CI_WORKFLOW not set)}': app tags are built by the $RL_RELEASE_WORKFLOW, $RL_BETA_WORKFLOW and $RL_SUBMIT_WORKFLOW workflows only" ;;
		esac
		[ -n "$build" ] || rl_fail "tag $tag: CI_BUILD_NUMBER is not set"
	fi
	case "$workflow" in
	"$RL_RELEASE_WORKFLOW")
		[ -n "$tag" ] || rl_fail "the $workflow workflow builds app tags only (ios-vX.Y.Z)"
		[ "$RL_KIND" = release ] || rl_fail "$tag is a pre-release: it goes to TestFlight through the $RL_BETA_WORKFLOW workflow, never to App Review. This $workflow run stops here on purpose."
		rl_has_changelog_section "$RL_VERSION" || rl_fail "ios/CHANGELOG.md has no '## $RL_VERSION' section (the App Store \"What's New\")"
		;;
	"$RL_BETA_WORKFLOW")
		[ -n "$tag" ] || rl_fail "the $workflow workflow builds app pre-release tags only (ios-beta-vX.Y.Z-beta.N)"
		[ "$RL_KIND" = beta ] || rl_fail "$tag is a release tag: the $RL_RELEASE_WORKFLOW workflow builds it. This $workflow run stops here on purpose."
		;;
	esac
	if [ -n "$build" ]; then
		[[ "$build" =~ ^[1-9][0-9]*$ ]] || rl_fail "CI_BUILD_NUMBER '$build' is not a positive integer"
	fi
	rl_write_xcconfig "$RL_VERSION" "$build"
}

# rl_write_xcconfig <marketing version or empty> <build number or empty>:
# atomic write of Config/CI.xcconfig (an empty value keeps the one of
# Config.xcconfig).
rl_write_xcconfig() {
	local tmp="$RL_CI_XCCONFIG.tmp"
	{
		echo "// Generated by ios/ci_scripts (Xcode Cloud, milestone M17). Never committed."
		[ -z "$1" ] || echo "MARKETING_VERSION = $1"
		[ -z "$2" ] || echo "CURRENT_PROJECT_VERSION = $2"
	} >"$tmp"
	mv "$tmp" "$RL_CI_XCCONFIG"
	rl_log "version ${1:-(from Config.xcconfig)}, build ${2:-(from Config.xcconfig)}${CI_TAG:+, tag $CI_TAG}${CI_WORKFLOW:+, workflow $CI_WORKFLOW}"
}

# rl_has_asc_key: whether the App Store Connect API key is set (secret
# environment variables of the Xcode Cloud workflow). Tests against a local
# mock (ASC_TEST_MODE=1 and ASC_API_BASE) need no key: AppStoreConnect.swift
# then signs with a throwaway key and checks the address itself.
rl_has_asc_key() {
	[ -n "${ASC_KEY_ID:-}" ] && [ -n "${ASC_ISSUER_ID:-}" ] && {
		[ -n "${ASC_PRIVATE_KEY:-}" ] || [ -n "${ASC_PRIVATE_KEY_PATH:-}" ] ||
			{ [ "${ASC_TEST_MODE:-}" = 1 ] && [ -n "${ASC_API_BASE:-}" ]; }
	}
}
